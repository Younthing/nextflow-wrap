/**
 * Config pieces for a generated project: a plain Nextflow pipeline with local
 * modules and no plugins. Groovy `${…}` is written as `@{…}` (see `nf`).
 */
import { BANNER, nf } from "./groovy";
import { runtimeProfiles } from "./launch";

export interface ProjectMeta {
  /** Repository-style name, e.g. `studio/scrna`. */
  name: string;
  /** Lowercase short name, e.g. `scrna`. */
  shortName: string;
  /** Upper-case workflow name, e.g. `SCRNA`. */
  workflowName: string;
  description: string;
  author: string;
  version: string;
}

export const NEXTFLOW_VERSION = "25.10.4";

const PROFILES = `${runtimeProfiles()}
    arm64 {
        process.arch            = 'arm64'
        apptainer.ociAutoPull   = true
        singularity.ociAutoPull = true
        wave.enabled            = true
        wave.freeze             = true
        wave.strategy           = 'conda,container'
    }
    emulate_amd64 {
        docker.runOptions       = '-u $(id -u):$(id -g) --platform=linux/amd64'
    }
    wave {
        apptainer.ociAutoPull   = true
        singularity.ociAutoPull = true
        wave.enabled            = true
        wave.freeze             = true
        wave.strategy           = 'conda,container'
    }
    gpu {
        docker.runOptions       = '-u $(id -u):$(id -g) --gpus all'
        apptainer.runOptions    = '--nv'
        singularity.runOptions  = '--nv'
    }`;

export function nextflowConfig(meta: ProjectMeta, paramsBlock: string, registry: string): string {
  return nf`/*
${BANNER}
    ${meta.name} Nextflow config file
${BANNER}
    Generated by Nextflow Studio. Pick a software runtime with -profile
    (conda, docker, apptainer, ...); without one, tasks run in the plain shell.
----------------------------------------------------------------------------------------
*/

params {
${paramsBlock}
}

includeConfig 'conf/base.config'

profiles {
    debug {
        dumpHashes              = true
        process.beforeScript    = 'echo $HOSTNAME'
        cleanup                 = false
        nextflow.enable.configProcessNamesValidation = true
    }
${PROFILES}
}

// Container registry used when a module only names an image
apptainer.registry    = '${registry}'
docker.registry       = '${registry}'
podman.registry       = '${registry}'
singularity.registry  = '${registry}'
charliecloud.registry = '${registry}'

process.shell = [ "bash", "-C", "-e", "-u", "-o", "pipefail" ]

nextflow.enable.configProcessNamesValidation = false

timeline {
    enabled = true
    file    = "@{params.outdir}/pipeline_info/execution_timeline_@{params.trace_report_suffix}.html"
}
report {
    enabled = true
    file    = "@{params.outdir}/pipeline_info/execution_report_@{params.trace_report_suffix}.html"
}
trace {
    enabled = true
    file    = "@{params.outdir}/pipeline_info/execution_trace_@{params.trace_report_suffix}.txt"
}

manifest {
    name            = '${meta.name}'
    contributors    = [ [ name: '${meta.author}', contribution: ['author'] ] ]
    description     = """${meta.description}"""
    mainScript      = 'main.nf'
    nextflowVersion = '!>=${NEXTFLOW_VERSION}'
    version         = '${meta.version}'
}

includeConfig 'conf/modules.config'
`;
}

export function baseConfig(meta: ProjectMeta): string {
  return nf`/*
${BANNER}
    ${meta.name} Nextflow base config file
${BANNER}
    A 'blank slate' config file, appropriate for general use on most high performance
    compute environments. Assumes that all software is installed and available on
    the PATH. Runs in \`local\` mode - all jobs will be run on the logged in environment.
----------------------------------------------------------------------------------------
*/

process {

    cpus   = { 1      * task.attempt }
    memory = { 6.GB   * task.attempt }
    time   = { 4.h    * task.attempt }

    errorStrategy = { task.exitStatus in ((130..145) + 104 + (175..177)) ? 'retry' : 'finish' }
    maxRetries    = 1
    maxErrors     = '-1'

    withLabel:process_single {
        cpus   = { 1                   }
        memory = { 6.GB * task.attempt }
        time   = { 4.h  * task.attempt }
    }
    withLabel:process_low {
        cpus   = { 2     * task.attempt }
        memory = { 12.GB * task.attempt }
        time   = { 4.h   * task.attempt }
    }
    withLabel:process_medium {
        cpus   = { 6     * task.attempt }
        memory = { 36.GB * task.attempt }
        time   = { 8.h   * task.attempt }
    }
    withLabel:process_high {
        cpus   = { 12    * task.attempt }
        memory = { 72.GB * task.attempt }
        time   = { 16.h  * task.attempt }
    }
    withLabel:process_long {
        time   = { 20.h  * task.attempt }
    }
    withLabel:process_low_memory {
        memory = { 1.GB * task.attempt }
    }
    withLabel:process_high_memory {
        memory = { 200.GB * task.attempt }
    }
    withLabel:error_ignore {
        errorStrategy = 'ignore'
    }
    withLabel:error_retry {
        errorStrategy = 'retry'
        maxRetries    = 2
    }
    withLabel: process_gpu {
        accelerator = { workflow.profile.contains('gpu') ? 1 : null }
    }
}
`;
}

